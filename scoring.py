"""Система баллов, подсказок и званий."""

# Словарь баллов в зависимости от количества использованных подсказок
HINT_POINTS = {0: 100, 1: 80, 2: 60, 3: 40}


def task_points(correct: bool, hints_used: int) -> int:
    """Баллы за задание: 100/80/60/40 или 0."""
    if not correct:
        return 0
    # Если подсказок больше 3, защита вернет 40 (минимум)
    return HINT_POINTS.get(hints_used, 40)


def get_rank(score: int) -> str:
    """Звание по итоговому баллу (из 600)."""
    if score >= 540:
        return "Эксперт цифровой безопасности"
    if score >= 420:
        return "Опытный защитник"
    if score >= 300:
        return "Начинающий специалист"
    return "Требуется дополнительное обучение"